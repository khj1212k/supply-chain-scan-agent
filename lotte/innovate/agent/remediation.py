"""조치안 에이전트 (OpenAI Agents SDK 0.24.0). 기획안 2-2, 5절 11~13번을 작게.

흐름 (코드가 바깥 루프를 쥔다)
  시도 k (최대 3):
    1. 조치안 에이전트 1회 실행: 읽기 전용 도구로 조사 -> submit_plan 으로 RemediationPlan 제출
       - 입력 가드레일(코드): 조치 요청 형식인지, 사례가 있는지
       - 출력 가드레일(코드): target_version 이 코드가 준 후보 안인지, also_bump 버전이 레지스트리에 있는지 (환각 차단)
       - 트립은 실패 1회로 세고, 사유를 다음 시도에 붙인다
    2. 기계 판정(judge.py): go get, tidy, build, test, 재스캔
    3. 실패면 판정 로그를 붙여 다음 시도
  통과하면: PR 작성 에이전트가 open_fix_pr(needs_approval=True)를 부른다 -> 실행이 멈춘다(interruptions)
            -> 사람 승인(CLI y/n, 일괄 평가는 --auto-approve 로 자동 승인하고 건수 기록) -> 재개 -> 로컬 패치 파일

모델은 agent/model_config.py 의 LAB_MODEL 한 줄로 바꾼다.
LiteLLM 1.83 은 claude-sonnet-5-5 에 output_type(JSON 스키마)을 강제 도구 호출로 바꿔 보내 400 이 난다
(Sonnet 5.5 는 tool_choice any/tool 을 거부). 그래서 output_type 대신 최종 제출 도구 + StopAtTools 를 쓴다.
"""
